package backend

// unit — the QML fixtures' drift guard (reader.qml_chart Decision 3;
// docs/remarkable-reader.md §6: `rows` are chartRows exactly, each shape's
// `model` is diagramModel). The songs under qml/tests/fixtures/songs/ were
// written for these tests. Each is committed into a local book with the views'
// machinery (newViewsFixture, the built bundle), opened through Serve as the
// frontend opens it (`open song`), and its `105 sheet` serialised as
// qml/tests/fixtures/<name>.js — the sheet the QML chart tests read. With
// -update-qml-fixtures the files are written; without it, the test fails when
// a committed fixture differs from what the backend answers now. A few
// variants (reader.song_screen) are the same songs opened with other state:
// a voicing hidden, the device's key, the account's saved key. One more,
// found-shape (reader.missed_shapes), holds a `105 sheet` with one empty place
// and the `108 shapes` the background search sends for it. To write them:
//
//	go test ./internal/backend -run TestQMLFixtures -update-qml-fixtures

import (
	"bytes"
	"context"
	"encoding/json"
	"errors"
	"flag"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"testing"

	"estantedecifras.app/remarkable/internal/engine"
	"estantedecifras.app/remarkable/internal/protocol"
	"estantedecifras.app/remarkable/internal/store"
)

var updateQMLFixtures = flag.Bool("update-qml-fixtures", false,
	"write qml/tests/fixtures/*.js from the fixture songs instead of checking them")

const qmlFixtureDir = "../../qml/tests/fixtures"

// qmlFixture is the QML-side file for one sheet: a library holding `sheet`.
func qmlFixture(t *testing.T, name, from string, sheet any) []byte {
	t.Helper()
	raw, err := json.MarshalIndent(sheet, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	var b bytes.Buffer
	b.WriteString(".pragma library\n")
	b.WriteString("// Generated by TestQMLFixtures (remarkable/internal/backend/qmlfixtures_test.go)\n")
	b.WriteString("// from fixtures/songs/" + from + ": the backend's `105 sheet` for it.\n")
	b.WriteString("// Do not edit; regenerate with -update-qml-fixtures (remarkable/README.md).\n")
	b.WriteString("var sheet = ")
	b.Write(raw)
	b.WriteString(";\n")
	return b.Bytes()
}

// foundShapeFixture is the QML-side file for a sheet and the `108 shapes`
// that followed it: a library holding `sheet` and `shapes`.
func foundShapeFixture(t *testing.T, from string, sheet protocol.Sheet, shapes protocol.Shapes) []byte {
	t.Helper()
	rawSheet, err := json.MarshalIndent(sheet, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	rawShapes, err := json.MarshalIndent(shapes, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	var b bytes.Buffer
	b.WriteString(".pragma library\n")
	b.WriteString("// Generated by TestQMLFixtures (remarkable/internal/backend/qmlfixtures_test.go)\n")
	b.WriteString("// from fixtures/songs/" + from + ": the backend's `105 sheet` for it, and\n")
	b.WriteString("// the `108 shapes` its background search sent next.\n")
	b.WriteString("// Do not edit; regenerate with -update-qml-fixtures (remarkable/README.md).\n")
	b.WriteString("var sheet = ")
	b.Write(rawSheet)
	b.WriteString(";\nvar shapes = ")
	b.Write(rawShapes)
	b.WriteString(";\n")
	return b.Bytes()
}

// noFill is the engine searching nothing in the background (its Fill fails,
// so the filler skips every miss): the sheet fixtures pin each 105 as sent,
// its empty places included, and the shared built engine's session stays as
// the table made it.
type noFill struct{ Engine }

func (noFill) Fill(context.Context, string) (engine.Filled, error) {
	return engine.Filled{}, errors.New("no background search for the sheet fixtures")
}

// foundShapeChord is the chord the found-shape fixture leaves missing: a
// default (choro-long's voicing block does not choose it) the song has in its
// first section and its second, so on its first page and its second.
const foundShapeChord = "E7"

func TestQMLFixtures(t *testing.T) {
	paths, err := filepath.Glob(filepath.Join(qmlFixtureDir, "songs", "*.cifra.md"))
	if err != nil {
		t.Fatal(err)
	}
	if len(paths) == 0 {
		t.Fatalf("no fixture songs under %s/songs", qmlFixtureDir)
	}
	sort.Strings(paths)
	f := newViewsFixture(t)
	var names []string
	for _, p := range paths {
		raw, err := os.ReadFile(p)
		if err != nil {
			t.Fatal(err)
		}
		base := filepath.Base(p)
		if _, taken := f.book[base]; taken {
			t.Fatalf("fixture song %s shadows a song of the views' book", base)
		}
		f.book[base] = string(raw)
		names = append(names, base)
	}
	f.commitBook(t)
	s := f.serve(t, noFill{builtEngine(t)})

	want := map[string]bool{}
	// write writes (with -update-qml-fixtures) or checks one fixture file.
	write := func(name, from string, got []byte) {
		t.Helper()
		file := filepath.Join(qmlFixtureDir, name+".js")
		want[name+".js"] = true
		if *updateQMLFixtures {
			if err := os.WriteFile(file, got, 0o644); err != nil {
				t.Fatal(err)
			}
			return
		}
		committed, err := os.ReadFile(file)
		if err != nil {
			t.Errorf("%s: %v — regenerate with -update-qml-fixtures", file, err)
			return
		}
		if !bytes.Equal(committed, got) {
			t.Errorf("%s has drifted from what the backend answers for %s — regenerate with -update-qml-fixtures and read the difference", file, from)
		}
	}
	check := func(name, from string, sheet protocol.Sheet) {
		t.Helper()
		write(name, from, qmlFixture(t, name, from, sheet))
	}
	sheets := map[string]protocol.Sheet{}
	for _, base := range names {
		name := strings.TrimSuffix(base, ".cifra.md")
		sheet := s.openSong(t, base, nil)
		if len(sheet.Rows) == 0 || string(sheet.Rows) == "null" {
			t.Fatalf("%s: the sheet has no rows", base)
		}
		sheets[name] = sheet
		check(name, base, sheet)
	}

	// The variants (reader.song_screen): the same songs with other state of the
	// device or the account, through the same machinery.
	//
	// choro-long-hidden: the store hiding the first shape of the song (so one
	// of its first page's), shown again afterwards so no other song sees it.
	const choroLong, fewChords = "choro-long.cifra.md", "few-chords.cifra.md"
	if _, ok := sheets["choro-long"]; !ok {
		t.Fatal("no choro-long fixture song")
	}
	if _, ok := sheets["few-chords"]; !ok {
		t.Fatal("no few-chords fixture song")
	}
	first := sheets["choro-long"].Shapes[0]
	if first.Frets == nil {
		t.Fatal("choro-long's first shape is pending")
	}
	hidden := store.Voicing{TuningID: sheets["choro-long"].TuningID, Chord: first.Chord, Frets: *first.Frets}
	if err := f.st.Hide(hidden); err != nil {
		t.Fatal(err)
	}
	check("choro-long-hidden", choroLong+" with its first shape hidden", s.openSong(t, choroLong, nil))
	if err := f.st.Show(hidden); err != nil {
		t.Fatal(err)
	}
	// few-chords-up2: the device's key at +2, then forgotten.
	two := 2
	if err := f.st.SetKey(testBook, fewChords, &two); err != nil {
		t.Fatal(err)
	}
	check("few-chords-up2", fewChords+" with the device's key at +2", s.openSong(t, fewChords, nil))
	if err := f.st.SetKey(testBook, fewChords, nil); err != nil {
		t.Fatal(err)
	}
	// few-chords-saved: a saved transposition of +2 in the home book's
	// songs.json (Your key: A), read by a backend started after it synced.
	s.stop()
	home := homeFiles(t, true)
	var songs map[string]any
	if err := json.Unmarshal([]byte(home["songs.json"]), &songs); err != nil {
		t.Fatal(err)
	}
	songs[testBook+"/"+fewChords] = map[string]any{"transposition": reg(2)}
	home["songs.json"] = mustMarshal(t, songs)
	commit(t, f.st.HomeDir(), home)
	s = f.serve(t, noFill{builtEngine(t)})
	check("few-chords-saved", fewChords+" with a saved transposition of +2", s.openSong(t, fewChords, nil))

	// found-shape (reader.missed_shapes): choro-long read by an engine of its
	// own, its table lacking foundShapeChord and every other miss searched
	// beforehand, so its 105 has that one place empty; then the 108 the
	// backend's background search sends for it.
	s.stop()
	s = f.serve(t, foundShapeEngine(t, fixtureSongText(t, choroLong)))
	sheet := s.openSong(t, choroLong, nil)
	var empty []string
	for _, sh := range sheet.Shapes {
		if isNull(sh.Model) {
			empty = append(empty, sh.Symbol)
		}
	}
	if len(empty) != 1 || empty[0] != foundShapeChord {
		t.Fatalf("found-shape's 105 leaves %v empty, want only %s", empty, foundShapeChord)
	}
	var found protocol.Shapes
	s.expect(t, protocol.TypeShapes, &found)
	for _, sh := range found.Shapes {
		if isNull(sh.Model) {
			t.Fatalf("found-shape's 108 leaves %s empty", sh.Symbol)
		}
	}
	write("found-shape", choroLong+" with "+foundShapeChord+" missing, then found",
		foundShapeFixture(t, choroLong+" with "+foundShapeChord+" missing, then found", sheet, found))

	// A fixture with no song behind it would be read by the QML tests and held
	// by nothing.
	stale, err := filepath.Glob(filepath.Join(qmlFixtureDir, "*.js"))
	if err != nil {
		t.Fatal(err)
	}
	for _, p := range stale {
		if !want[filepath.Base(p)] {
			t.Errorf("%s has no fixture song behind it", p)
		}
	}
}

// fixtureSongText is a fixture song's text, read from fixtures/songs.
func fixtureSongText(t *testing.T, base string) string {
	t.Helper()
	raw, err := os.ReadFile(filepath.Join(qmlFixtureDir, "songs", base))
	if err != nil {
		t.Fatal(err)
	}
	return string(raw)
}

// foundShapeEngine opens the built bundle on the example book's entry and its
// table less foundShapeChord's entry, and searches beforehand, in its session,
// every other chord text leaves pending — so foundShapeChord is the one miss
// queued when the backend reads text.
func foundShapeEngine(t *testing.T, text string) *engine.Engine {
	t.Helper()
	builtEngine(t) // fails the test when the build is missing
	raw, err := os.ReadFile(fixtureFile)
	if err != nil {
		t.Fatal(err)
	}
	var fx struct {
		Entry json.RawMessage `json:"entry"`
		Table struct {
			Fingerprint string                     `json:"fingerprint"`
			Shapes      map[string]json.RawMessage `json:"shapes"`
		} `json:"table"`
	}
	if err := json.Unmarshal(raw, &fx); err != nil {
		t.Fatal(err)
	}
	ctx := context.Background()
	open := func(table json.RawMessage) *engine.Engine {
		e, err := engine.Open(bundleDir)
		if err != nil {
			t.Fatal(err)
		}
		t.Cleanup(func() { e.Close() })
		if _, err := e.Load(ctx, fx.Entry, table); err != nil {
			t.Fatal(err)
		}
		if _, err := e.Sheet(ctx, text, 0, engine.SheetOptions{}); err != nil {
			t.Fatal(err)
		}
		return e
	}

	// The chord's table key: what a bundle with no table queues for it.
	bare := open(nil)
	misses, err := bare.Misses(ctx)
	if err != nil {
		t.Fatal(err)
	}
	key := ""
	for _, m := range misses {
		if m.Symbol == foundShapeChord {
			key = m.Chord
		}
	}
	if _, ok := fx.Table.Shapes[key]; key == "" || !ok {
		t.Fatalf("the example table holds no %s for the song", foundShapeChord)
	}
	bare.Close()
	delete(fx.Table.Shapes, key)
	table, err := json.Marshal(fx.Table)
	if err != nil {
		t.Fatal(err)
	}

	e := open(table)
	if misses, err = e.Misses(ctx); err != nil {
		t.Fatal(err)
	}
	kept := false
	for _, m := range misses {
		if m.Chord == key {
			kept = true
			continue
		}
		if got, err := e.Fill(ctx, m.Chord); err != nil || !got.Searched {
			t.Fatalf("searching %s beforehand: %+v, %v", m.Symbol, got, err)
		}
	}
	if !kept {
		t.Fatalf("%s is not pending in the song", foundShapeChord)
	}
	return e
}
