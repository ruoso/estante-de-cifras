// browseFixtures writes (or checks) browse-shelf, browse-book,
// browse-book-small, browse-setlist, browse-settings and
// browse-settings-update from the backend's
// views over the books built from fixtures/browse-book/.
func browseFixtures(t *testing.T, write func(name, from string, got []byte)) {
	t.Helper()
	dir := filepath.Join(qmlFixtureDir, "browse-book")
	entries, err := os.ReadDir(dir)
	if err != nil {
		t.Fatal(err)
	}
	files := map[string]string{}
	var songs []string
	for _, e := range entries {
		raw, err := os.ReadFile(filepath.Join(dir, e.Name()))
		if err != nil {
			t.Fatal(err)
		}
		files[e.Name()] = string(raw)
		if strings.HasSuffix(e.Name(), songSuffix) {
			songs = append(songs, e.Name())
		}
	}
	sort.Strings(songs)
	if len(songs) != 34 {
		t.Fatalf("fixtures/browse-book holds %d songs, want 34", len(songs))
	}
	pick := func(names ...string) map[string]string {
		out := map[string]string{}
		for _, n := range names {
			text, ok := files[n]
			if !ok {
				t.Fatalf("fixtures/browse-book has no %s", n)
			}
			out[n] = text
		}
		return out
	}

	root := t.TempDir()
	st, err := store.Open(root)
	if err != nil {
		t.Fatal(err)
	}
	books := map[string]map[string]string{
		browseBook:     files,
		browseSmall:    pick(append(append([]string{}, songs[:12]...), "ensaio-de-quinta.setlist.md", "so-uma.setlist.md")...),
		browseUntitled: pick("aria-do-porto.cifra.md", "so-uma.setlist.md"),
		browseRoda:     pick(songs[12:24]...),
	}
	for id, fs := range books {
		bd, err := st.BookDir(id)
		if err != nil {
			t.Fatal(err)
		}
		commit(t, bd, fs)
	}
	shelf := map[string]any{
		browseBook:     map[string]any{"link": reg("https://example.test/git/" + browseBook), "position": reg(1), "label": reg("Banda do Bairro")},
		browseSmall:    map[string]any{"link": reg("https://example.test/git/" + browseSmall), "position": reg(2), "label": reg("Choro na Varanda")},
		browseUntitled: map[string]any{"link": reg("https://example.test/git/" + browseUntitled), "position": reg(3)},
		browseRoda:     map[string]any{"link": reg("https://example.test/git/" + browseRoda), "position": reg(4), "label": reg("Roda de Quinta")},
		noClone:        map[string]any{"link": reg("https://example.test/git/" + noClone), "position": reg(5)},
	}
	commit(t, st.HomeDir(), map[string]string{
		"shelf.json": mustMarshal(t, map[string]any{"books": shelf}),
		"songs.json": mustMarshal(t, map[string]any{}),
	})
	if err := st.SetSession(store.Session{Origin: "https://example.test", Token: "t", Account: browseAccount}); err != nil {
		t.Fatal(err)
	}
	for i := 0; i < browseHidden; i++ {
		v := store.Voicing{TuningID: "40 45 50 55 59 64", Chord: "C:", Frets: fmt.Sprintf("x3201%d", i)}
		if err := st.Hide(v); err != nil {
			t.Fatal(err)
		}
	}

	f := &viewsFixture{root: root, st: st, book: books[browseBook]}
	s := f.serve(t, noFill{builtEngine(t)})
	defer s.stop()
	const from = "fixtures/browse-book/"

	s.send(t, protocol.TypeOpen, map[string]any{"view": "shelf"})
	var sh protocol.Shelf
	s.expect(t, protocol.TypeShelf, &sh)
	if len(sh.Books) != 4 {
		t.Fatalf("the browse shelf has %d books, want 4", len(sh.Books))
	}
	write("browse-shelf", from, browseFixture(t, "shelf", "the books built from "+from+": the backend's `103 shelf`", sh))

	openBook := func(id string) protocol.Book {
		t.Helper()
		s.send(t, protocol.TypeOpen, map[string]any{"view": "book", "bookId": id})
		var b protocol.Book
		s.expect(t, protocol.TypeBook, &b)
		if b.BookID != id {
			t.Fatalf("opened %s, got book %s", id, b.BookID)
		}
		return b
	}
	big := openBook(browseBook)
	if len(big.Songs) != 34 || len(big.Setlists) != 3 {
		t.Fatalf("the browse book has %d songs and %d setlists, want 34 and 3", len(big.Songs), len(big.Setlists))
	}
	write("browse-book", from, browseFixture(t, "book", from+": the backend's `104 book`", big))
	small := openBook(browseSmall)
	if n := len(small.Songs) + len(small.Setlists); n <= 10 || n > 20 {
		t.Fatalf("the small browse book has %d rows, want two pages", n)
	}
	write("browse-book-small", from, browseFixture(t, "book", "twelve songs and two setlists of "+from+": the backend's `104 book`", small))

	s.send(t, protocol.TypeOpen, map[string]any{"view": "setlist", "bookId": browseBook, "path": browseSetlist})
	var set protocol.Setlist
	s.expect(t, protocol.TypeSetlist, &set)
	if len(set.Items) != 14 {
		t.Fatalf("the browse setlist has %d items, want 14", len(set.Items))
	}
	write("browse-setlist", from, browseFixture(t, "setlist", from+browseSetlist+": the backend's `106 setlist`", set))

	s.send(t, protocol.TypeOpen, map[string]any{"view": "settings"})
	var settings protocol.Settings
	s.expect(t, protocol.TypeSettings, &settings)
	if settings.HiddenShapes != browseHidden || settings.Account != browseAccount {
		t.Fatalf("browse settings %+v", settings)
	}
	write("browse-settings", from, browseFixture(t, "settings", "a reader paired with "+browseAccount+" hiding "+fmt.Sprint(browseHidden)+" voicings: the backend's `107 settings`", settings))

	// reader.self_update: the site serves a hostApi newer than this backend
	// speaks, so the settings say *Update the reader on your reMarkable*.
	if err := st.SetServedHostAPI(engine.HostAPI + 1); err != nil {
		t.Fatal(err)
	}
	s.send(t, protocol.TypeOpen, map[string]any{"view": "settings"})
	var tooOld protocol.Settings
	s.expect(t, protocol.TypeSettings, &tooOld)
	if !tooOld.UpdateReader {
		t.Fatalf("browse settings, too old %+v", tooOld)
	}
	write("browse-settings-update", from, browseFixture(t, "settings", "a reader paired with "+browseAccount+" hiding "+fmt.Sprint(browseHidden)+" voicings, the site serving a newer hostApi: the backend's `107 settings`", tooOld))
	if err := st.SetServedHostAPI(engine.HostAPI); err != nil {
		t.Fatal(err)
	}

	// The played sheets (reader.play): items of the browse setlist opened
	// playing, each its `105 sheet` and the `109 ahead`s that follow it — the
	// first item, the one before the missing item 3, the one after it, the
	// keyless song the setlist gives a key, and the last two.
	for _, at := range playFixtureItems {
		s.send(t, protocol.TypeOpen, map[string]any{"view": "song", "bookId": browseBook,
			"path": set.Items[at].Path, "play": map[string]any{"setlist": browseSetlist, "at": at}})
		sheet := s.sheet(t)
		if sheet.Play == nil || sheet.Play.At != at {
			t.Fatalf("played item %d: play %+v", at, sheet.Play)
		}
		n := 2
		if at == 0 || at == len(set.Items)-1 {
			n = 1
		}
		var ahead []protocol.Sheet
		for i := 0; i < n; i++ {
			ahead = append(ahead, s.ahead(t))
		}
		name := fmt.Sprintf("play-%d", at)
		write(name, from, playFixture(t, from+browseSetlist+" item "+fmt.Sprint(at), sheet, ahead))
	}
}

